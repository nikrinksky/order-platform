package com.orderplatform.order.client;

/**
 * Абстракция инвентарь-сервиса для order-service.
 *
 * <p>Назначение — отделить бизнес-логику заказа от HTTP-деталей и сделать
 * операции с остатками тестируемыми без URL-паттернов. Реализация по
 * умолчанию — {@link RestTemplateInventoryClient}.</p>
 */
public interface InventoryClient {

    /**
     * Резервирует указанный объём товара под заказ.
     *
     * <p>Успехом считается только явное подтверждение inventory-service:
     * пустой ответ или ошибка означают, что резерв не подтверждён.</p>
     *
     * <p>Это и есть проверка наличия: отдельный fail-open предварительный запрос
     * остатка пропускал заказ при недоступном inventory, а затем резерв всё равно
     * не подтверждался, поэтому заказ создавался без товара.</p>
     *
     * @param productId идентификатор товара
     * @param quantity  резервируемое количество
     * @param orderId   идентификатор заказа
     * @return true если резервирование выполнено
     */
    boolean reserve(String productId, int quantity, String orderId);

    /**
     * Освобождает ранее зарезервированный объём товара.
     *
     * @param productId идентификатор товара
     * @param quantity  освобождаемое количество
     * @param orderId   идентификатор заказа
     */
    void release(String productId, int quantity, String orderId);

    /**
     * Списывает остаток, удерживаемый заказом, — товар покинул склад.
     *
     * <p>Отличается от {@link #release}: при списании единицы уходят и из свободного
     * остатка, и из общего количества, потому что товара больше нет. Операция
     * идемпотентна по заказу, поэтому повторный вызов безопасен.</p>
     *
     * <p>В отличие от release, ошибка здесь не глотается: заказ нельзя перевести в
     * COMPLETED, пока товар не списан, иначе остатки навсегда разойдутся с фактом.</p>
     *
     * @param orderId идентификатор заказа
     * @return true если inventory-service подтвердил списание
     */
    boolean commit(String orderId);
}
